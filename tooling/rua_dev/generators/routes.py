"""Generate the per-route HTTP methods of the Rust, Python and TypeScript SDKs.

Reads schemas/openapi.json, which `hebbian-robot-use-server schema --openapi` writes from
the routes in station/src/openapi.rs, for every operation marked `x-sdk`. Response and
request types are the contract types the SDKs already generate from the Rust types
(`hebbian_contracts`; `contract/station_api.py` and `generated/api-schemas.ts` are generated from the same document's components).
"""

import re
from dataclasses import dataclass
from pathlib import Path

from rua_dev.models import SdkTarget

RUST_PATH = Path("sdk/src/generated/http_routes.rs")
PYTHON_PATH = Path(
    "hebbian_robot_use_client/hebbian_robot_use_client/contract/http_routes.py"
)
TYPESCRIPT_PATH = Path("typescript-client/src/generated/http-routes.ts")
HEADER = "Generated by rua-dev contracts from schemas/openapi.json."


@dataclass(frozen=True)
class Reply:
    """What an operation answers: a JSON `schema`, nothing (`unit`) or a raw `file`."""

    kind: str
    schema: dict | None = None


@dataclass(frozen=True)
class Operation:
    name: str
    method: str
    path: str
    server: str
    summary: str
    path_parameters: list[str]
    body: dict | None
    reply: Reply
    sends_lease_token: bool

    @property
    def segments(self) -> list[str]:
        return self.path.strip("/").split("/")

    @property
    def camel_name(self) -> str:
        return snake_to_camel(self.name)


def snake_to_camel(name: str) -> str:
    first, *rest = name.split("_")
    return first + "".join(part.capitalize() for part in rest)


def load_operations(document: dict) -> list[Operation]:
    components = document["components"]["schemas"]
    operations = []
    for path, methods in document["paths"].items():
        for method, operation in methods.items():
            if not operation["x-sdk"]:
                continue
            ok = next(
                response
                for status, response in operation["responses"].items()
                if status != "default"
            )
            content = ok.get("content")
            if content is None:
                reply = Reply("unit")
            elif "application/json" in content:
                schema = content["application/json"]["schema"]
                reply = (
                    Reply("unit")
                    if schema == {"type": "null"}
                    else Reply("json", schema)
                )
            else:
                reply = Reply("file")
            body = operation.get("requestBody")
            operations.append(
                Operation(
                    name=operation["operationId"],
                    method=method.upper(),
                    path=path,
                    server=operation["x-server"],
                    summary=operation["summary"],
                    path_parameters=re.findall(r"\{(\w+)\}", path),
                    body=body["content"]["application/json"]["schema"]
                    if body
                    else None,
                    reply=reply,
                    sends_lease_token=bool(
                        body
                        and "lease_token"
                        in components.get(
                            reference_name(
                                body["content"]["application/json"]["schema"]
                            )
                            or "",
                            {},
                        ).get("properties", {})
                    ),
                )
            )
    return operations


def reference_name(schema: dict) -> str | None:
    return schema["$ref"].rsplit("/", 1)[1] if "$ref" in schema else None


def nullable_inner(schema: dict) -> dict | None:
    """The non-null alternative of `anyOf: [X, null]`."""
    alternatives = schema.get("anyOf")
    if alternatives and len(alternatives) == 2:
        inner = [alt for alt in alternatives if alt != {"type": "null"}]
        if len(inner) == 1:
            return inner[0]
    return None


# Rust ----------------------------------------------------------------------


def rust_type(schema: dict) -> str:
    inner = nullable_inner(schema)
    if inner is not None:
        return f"Option<{rust_type(inner)}>"
    name = reference_name(schema)
    if name:
        return name
    match schema["type"]:
        case "string":
            return "String"
        case "boolean":
            return "bool"
        case "array":
            return f"Vec<{rust_type(schema['items'])}>"
    raise ValueError(f"unsupported schema {schema}")


def rust_names(schema: dict) -> set[str]:
    return {
        match
        for match in re.findall(r"[A-Z]\w+", rust_type(schema))
        if match not in {"String", "Vec", "Option"}
    }


def rust_segments(operation: Operation) -> str:
    return ", ".join(
        segment[1:-1] if segment.startswith("{") else f'"{segment}"'
        for segment in operation.segments
    )


def generate_rust(operations: list[Operation]) -> str:
    names = set()
    for operation in operations:
        for schema in (operation.body, operation.reply.schema):
            if schema:
                names |= rust_names(schema)
    lines = [
        f"// {HEADER}",
        "use hebbian_contracts::{" + ", ".join(sorted(names)) + "};",
        "use reqwest::{Method, Response};",
        "",
        "use crate::{Result, Station};",
        "",
        "impl Station {",
    ]
    for operation in operations:
        parameters = ["&self"]
        parameters += [f"{name}: &str" for name in operation.path_parameters]
        if operation.body:
            parameters.append(f"body: &{rust_type(operation.body)}")
        returns = {
            "unit": "()",
            "file": "Response",
            "json": rust_type(operation.reply.schema or {})
            if operation.reply.schema
            else "",
        }[operation.reply.kind]
        base = "&self.media_server" if operation.server == "media" else "&self.server"
        body = "Some(body)" if operation.body else "None::<&()>"
        call = (
            f"self.request(Method::{operation.method}, {base}, "
            f"&[{rust_segments(operation)}], {body}).await"
        )
        # The lease token never leaves the SDK: `LeaseGuard` sends these routes.
        visibility = "pub(crate) " if operation.sends_lease_token else "pub "
        lines += [
            f"    /// {operation.summary}",
            "    ///",
            "    /// # Errors",
            "    /// [`crate::Error::Http`] with the service's status, or [`crate::Error::Connection`].",
            f"    {visibility}async fn {operation.name}({', '.join(parameters)}) -> Result<{returns}> {{",
        ]
        match operation.reply.kind:
            case "file":
                lines.append(f"        {call}")
            case "unit":
                lines += [f"        {call}?;", "        Ok(())"]
            case _:
                lines.append(f"        Ok({call}?.json().await?)")
        lines += ["    }", ""]
    lines[-1] = "}"
    return "\n".join(lines) + "\n"


# Python --------------------------------------------------------------------


def python_type(schema: dict, used: set[str], components: dict) -> str:
    """The annotation of a schema; `used` collects the `contract/station_api.py` models it names."""
    inner = nullable_inner(schema)
    if inner is not None:
        return f"{python_type(inner, used, components)} | None"
    name = reference_name(schema)
    if name:
        # Collapsed root unions are generated as their titled alternatives.
        component = components[name]
        alternatives = component.get("oneOf", [])
        if alternatives and all("title" in alternative for alternative in alternatives):
            names = [alternative["title"] for alternative in alternatives]
            used.update(names)
            return " | ".join(names)
        # A schema accepting any JSON value has no generated model.
        if True in component.get("anyOf", []):
            return "object"
        used.add(name)
        return name
    match schema["type"]:
        case "string":
            return "str"
        case "boolean":
            return "bool"
        case "array":
            return f"list[{python_type(schema['items'], used, components)}]"
    raise ValueError(f"unsupported schema {schema}")


def generate_python(operations: list[Operation], components: dict) -> str:
    used: set[str] = set()
    typed: dict[str, tuple[str | None, str | None]] = {}
    for operation in operations:
        body_type = response_type = None
        if operation.body:
            body_type = python_type(operation.body, used, components)
        if operation.reply.kind == "json" and operation.reply.schema:
            response_type = python_type(operation.reply.schema, used, components)
        typed[operation.name] = (body_type, response_type)
    lines = [
        f'"""{HEADER}"""',
        "",
        "from urllib.parse import quote",
        "",
        "import httpx2",
        "from pydantic import TypeAdapter",
        "",
    ]
    if used:
        lines += [
            "from hebbian_robot_use_client.contract.station_api import (",
            *[f"    {name}," for name in sorted(used)],
            ")",
        ]
    lines += [
        "",
        "",
        "class StationApi:",
        '    """One method per station HTTP route; the media service has its own client."""',
        "",
        "    def __init__(",
        "        self, station: httpx2.AsyncClient, media: httpx2.AsyncClient",
        "    ) -> None:",
        "        self._station = station",
        "        self._media = media",
        "",
        "    async def close(self) -> None:",
        "        await self._station.aclose()",
        "        await self._media.aclose()",
        "",
        "    @staticmethod",
        "    async def _send(",
        "        client: httpx2.AsyncClient,",
        "        method: str,",
        "        path: str,",
        "        body: object = None,",
        "    ) -> httpx2.Response:",
        "        response = await client.request(",
        "            method,",
        "            path,",
        "            content=None if body is None else TypeAdapter(object).dump_json(body),",
        '            headers=None if body is None else {"Content-Type": "application/json"},',
        "        )",
        "        response.raise_for_status()",
        "        return response",
        "",
    ]
    for operation in operations:
        body_type, response_type = typed[operation.name]
        parameters = ["self"] + [f"{name}: str" for name in operation.path_parameters]
        if body_type:
            parameters.append(f"body: {body_type}")
        returns = {"unit": "None", "file": "httpx2.Response"}.get(
            operation.reply.kind, response_type or "None"
        )
        path = "/".join(
            f"{{quote({segment[1:-1]}, safe='')}}"
            if segment.startswith("{")
            else segment
            for segment in operation.segments
        )
        client = "self._media" if operation.server == "media" else "self._station"
        send = f'await self._send({client}, "{operation.method}", f"/{path}"' + (
            ", body)" if body_type else ")"
        )
        lines += [
            f"    async def {operation.name}({', '.join(parameters)}) -> {returns}:",
            f'        """{operation.summary}"""',
        ]
        match operation.reply.kind:
            case "file":
                lines.append(f"        return {send}")
            case "unit":
                lines.append(f"        {send}")
            case _:
                lines += [
                    f"        response = {send}",
                    f"        return TypeAdapter({response_type}).validate_json(response.content)",
                ]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# TypeScript ----------------------------------------------------------------


def typescript_parser(schema: dict) -> str | None:
    """The zod expression that parses a response, or none for a type it cannot name."""
    inner = nullable_inner(schema)
    if inner is not None:
        parser = typescript_parser(inner)
        return None if parser is None else f"{parser}.nullable()"
    name = reference_name(schema)
    if name:
        return f"apiSchemas.shape.{name}"
    match schema["type"]:
        case "string":
            return "z.string()"
        case "boolean":
            return "z.boolean()"
        case "array":
            item = typescript_parser(schema["items"])
            return None if item is None else f"z.array({item})"
    raise ValueError(f"unsupported schema {schema}")


def typescript_body_type(schema: dict) -> str:
    name = reference_name(schema)
    assert name
    return f'ApiSchemas["{name}"]'


def generate_typescript(operations: list[Operation]) -> str:
    lines = [
        f"// {HEADER}",
        'import { z } from "zod";',
        "",
        'import { type ApiSchemas, apiSchemas } from "./api-schemas.js";',
        'import { jsonRequestInit, stationFetch, stationRequest } from "../station-request.js";',
        "",
        "/** One method per station HTTP route; the media service has its own address. */",
        "export function createStationApi(stationUrl: string | URL, mediaUrl: string | URL) {",
        "  return {",
    ]
    for operation in operations:
        parameters = [
            f"{snake_to_camel(name)}: string" for name in operation.path_parameters
        ]
        if operation.body:
            parameters.append(f"body: {typescript_body_type(operation.body)}")
        path = "/".join(
            f"${{encodeURIComponent({snake_to_camel(segment[1:-1])})}}"
            if segment.startswith("{")
            else segment
            for segment in operation.segments
        )
        base = "mediaUrl" if operation.server == "media" else "stationUrl"
        init = (
            f'jsonRequestInit("{operation.method}"{", body" if operation.body else ""})'
        )
        url = f"new URL(`/{path}`, {base})"
        lines += [
            f"    /** {operation.summary} */",
            f"    async {operation.camel_name}({', '.join(parameters)}) {{",
        ]
        parser = (
            typescript_parser(operation.reply.schema)
            if operation.reply.kind == "json" and operation.reply.schema
            else None
        )
        match operation.reply.kind:
            case "file":
                lines.append(f"      return stationFetch({url}, {init});")
            case "unit":
                lines.append(f"      await stationFetch({url}, {init});")
            case _ if parser:
                lines.append(
                    f"      return {parser}.parse(await stationRequest({url}, {init}));"
                )
            case _:
                lines.append(f"      return stationRequest({url}, {init});")
        lines += ["    },"]
    lines += ["  };", "}"]
    return "\n".join(lines) + "\n"


def generate(schema: dict, targets: frozenset[SdkTarget]) -> None:
    operations = load_operations(schema)
    if SdkTarget.RUST in targets:
        RUST_PATH.parent.mkdir(parents=True, exist_ok=True)
        RUST_PATH.write_text(generate_rust(operations))
    if SdkTarget.PYTHON in targets:
        PYTHON_PATH.write_text(
            generate_python(operations, schema["components"]["schemas"])
        )
    if SdkTarget.TYPESCRIPT in targets:
        TYPESCRIPT_PATH.write_text(generate_typescript(operations))
