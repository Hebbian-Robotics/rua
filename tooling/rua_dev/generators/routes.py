from __future__ import annotations

import re
from dataclasses import dataclass
from enum import Enum
from pathlib import Path
from typing import Literal, assert_never

from pydantic import BaseModel, Field, JsonValue

from rua_dev.models import SdkTarget

RUST_PATH = Path("sdk/src/generated/http_routes.rs")
TYPESCRIPT_PATH = Path("typescript-client/src/generated/http-routes.ts")
HEADER = "Generated by rua-dev contracts from schemas/openapi.json."


class OpenApiMedia(BaseModel):
    json_schema: JsonValue = Field(alias="schema")


class OpenApiResponse(BaseModel):
    content: dict[str, OpenApiMedia] | None = None


class OpenApiRequest(BaseModel):
    content: dict[str, OpenApiMedia]


class OpenApiOperation(BaseModel):
    operation_id: str = Field(alias="operationId")
    summary: str
    sdk: bool = Field(alias="x-sdk")
    direct_media: bool = Field(False, alias="x-direct-media")
    responses: dict[str, OpenApiResponse]
    request_body: OpenApiRequest | None = Field(None, alias="requestBody")


class OpenApiRoutes(BaseModel):
    paths: dict[str, dict[Literal["get", "post", "delete"], OpenApiOperation]]
    components: dict[str, dict[str, dict[str, JsonValue]]]


@dataclass(frozen=True)
class SchemaReference:
    name: str


@dataclass(frozen=True)
class NullableSchema:
    inner: RouteSchema


@dataclass(frozen=True)
class ArraySchema:
    item: RouteSchema


class ScalarSchema(Enum):
    STRING = "string"
    BOOLEAN = "boolean"


type RouteSchema = SchemaReference | NullableSchema | ArraySchema | ScalarSchema


@dataclass(frozen=True)
class JsonReply:
    schema: RouteSchema


class NonJsonReply(Enum):
    UNIT = "unit"
    FILE = "file"


type Reply = JsonReply | NonJsonReply


@dataclass(frozen=True)
class RequestBody:
    schema: SchemaReference
    sends_lease_token: bool


@dataclass(frozen=True)
class Operation:
    name: str
    method: str
    path: str
    direct_media: bool
    summary: str
    body: RequestBody | None
    reply: Reply

    @property
    def segments(self) -> list[str]:
        return self.path.strip("/").split("/")

    @property
    def path_parameters(self) -> list[str]:
        return re.findall(r"\{(\w+)\}", self.path)

    @property
    def camel_name(self) -> str:
        return snake_to_camel(self.name)


def snake_to_camel(name: str) -> str:
    first, *rest = name.split("_")
    return first + "".join(part.capitalize() for part in rest)


def parse_route_schema(schema: object) -> RouteSchema:
    match schema:
        case {"$ref": str(reference)} if reference.startswith("#/components/schemas/"):
            return SchemaReference(reference.rsplit("/", 1)[1])
        case {"type": "string" | "boolean" as scalar}:
            return ScalarSchema(scalar)
        case {"type": "array", "items": item}:
            return ArraySchema(parse_route_schema(item))
        case {"anyOf": [{"type": "null"}, inner] | [inner, {"type": "null"}]}:
            return NullableSchema(parse_route_schema(inner))
    raise ValueError(f"Unsupported route schema: {schema!r}")


def parse_reply(operation: OpenApiOperation) -> Reply:
    success = [
        response
        for status, response in operation.responses.items()
        if re.fullmatch(r"2[0-9]{2}", status)
    ]
    if len(success) != 1:
        raise ValueError("Expected exactly one success response")
    content = success[0].content
    if content is None:
        return NonJsonReply.UNIT
    json_media = content.get("application/json")
    if json_media is None:
        return NonJsonReply.FILE
    if json_media.json_schema == {"type": "null"}:
        return NonJsonReply.UNIT
    return JsonReply(parse_route_schema(json_media.json_schema))


def parse_operations(document: object) -> list[Operation]:
    route_document = OpenApiRoutes.model_validate(document)
    components = route_document.components["schemas"]
    operations = []
    for path, methods in route_document.paths.items():
        for method, operation in methods.items():
            if not operation.sdk:
                continue
            try:
                body = None
                if operation.request_body is not None:
                    schema = parse_route_schema(
                        operation.request_body.content["application/json"].json_schema
                    )
                    if not isinstance(schema, SchemaReference):
                        raise ValueError(
                            "Expected a component reference for the request body"
                        )
                    properties = components[schema.name].get("properties")
                    body = RequestBody(
                        schema,
                        isinstance(properties, dict) and "lease_token" in properties,
                    )
                reply = parse_reply(operation)
            except (KeyError, ValueError) as error:
                raise ValueError(
                    f"Invalid SDK route {method.upper()} {path}: {error}"
                ) from error
            operations.append(
                Operation(
                    operation.operation_id,
                    method.upper(),
                    path,
                    operation.direct_media,
                    operation.summary,
                    body,
                    reply,
                )
            )
    return operations


def rust_type(schema: RouteSchema) -> str:
    match schema:
        case SchemaReference(name):
            return name
        case NullableSchema(inner):
            return f"Option<{rust_type(inner)}>"
        case ArraySchema(item):
            return f"Vec<{rust_type(item)}>"
        case ScalarSchema.STRING:
            return "String"
        case ScalarSchema.BOOLEAN:
            return "bool"
    assert_never(schema)


def rust_names(schema: RouteSchema) -> set[str]:
    match schema:
        case SchemaReference(name):
            return {name}
        case NullableSchema(inner) | ArraySchema(inner):
            return rust_names(inner)
        case ScalarSchema.STRING | ScalarSchema.BOOLEAN:
            return set()
    assert_never(schema)


def rust_segments(operation: Operation) -> str:
    return ", ".join(
        segment[1:-1] if segment.startswith("{") else f'"{segment}"'
        for segment in operation.segments
    )


def generate_rust(operations: list[Operation]) -> str:
    names = set()
    for operation in operations:
        if operation.body is not None:
            names.add(operation.body.schema.name)
        if isinstance(operation.reply, JsonReply):
            names |= rust_names(operation.reply.schema)
    lines = [
        f"// {HEADER}",
        "use hebbian_contracts::{" + ", ".join(sorted(names)) + "};",
        "use reqwest::{Method, Response};",
        "",
        "use crate::{Result, Station};",
        "",
        "impl Station {",
    ]
    for operation in operations:
        parameters = ["&self"]
        parameters += [f"{name}: &str" for name in operation.path_parameters]
        if operation.body is not None:
            parameters.append(f"body: &{operation.body.schema.name}")
        reply = operation.reply
        match reply:
            case NonJsonReply.UNIT:
                returns = "()"
            case NonJsonReply.FILE:
                returns = "Response"
            case JsonReply(schema):
                returns = rust_type(schema)
            case _:
                assert_never(reply)
        base = "&self.media_server" if operation.direct_media else "&self.server"
        body = "Some(body)" if operation.body else "None::<&()>"
        call = (
            f"self.request(Method::{operation.method}, {base}, "
            f"&[{rust_segments(operation)}], {body}).await"
        )
        # INVARIANT: The lease token never leaves the SDK: `LeaseGuard` sends these routes.
        visibility = (
            "pub(crate) "
            if operation.body and operation.body.sends_lease_token
            else "pub "
        )
        lines += [
            f"    /// {operation.summary}",
            "    ///",
            "    /// # Errors",
            "    /// [`crate::Error::Http`] with the service's status, or [`crate::Error::Connection`].",
            f"    {visibility}async fn {operation.name}({', '.join(parameters)}) -> Result<{returns}> {{",
        ]
        match reply:
            case NonJsonReply.FILE:
                lines.append(f"        {call}")
            case NonJsonReply.UNIT:
                lines += [f"        {call}?;", "        Ok(())"]
            case JsonReply():
                lines.append(f"        Ok({call}?.json().await?)")
            case _:
                assert_never(reply)
        lines += ["    }", ""]
    lines[-1] = "}"
    return "\n".join(lines) + "\n"


def typescript_parser(schema: RouteSchema) -> str:
    match schema:
        case SchemaReference(name):
            return f"apiSchemas.shape.{name}"
        case NullableSchema(inner):
            return f"{typescript_parser(inner)}.nullable()"
        case ScalarSchema.STRING:
            return "z.string()"
        case ScalarSchema.BOOLEAN:
            return "z.boolean()"
        case ArraySchema(item):
            return f"z.array({typescript_parser(item)})"
    assert_never(schema)


def generate_typescript(operations: list[Operation]) -> str:
    lines = [
        f"// {HEADER}",
        'import { Effect } from "effect";',
        'import type { HttpClient } from "effect/http";',
        'import { z } from "zod";',
        "",
        'import { type ApiSchemas, apiSchemas } from "./api-schemas.js";',
        'import { runStationEffect, stationBinaryEffect, stationParsedJsonEffect, stationVoidEffect } from "../station-request.js";',
        "",
        "/** Effect-native station routes; the caller supplies the HTTP client service. */",
        "export function createStationEffectApi(stationUrl: string | URL, mediaUrl: string | URL) {",
        "  return {",
    ]
    for operation in operations:
        parameters = [
            f"{snake_to_camel(name)}: string" for name in operation.path_parameters
        ]
        if operation.body is not None:
            parameters.append(f'body: ApiSchemas["{operation.body.schema.name}"]')
        path = "/".join(
            f"${{encodeURIComponent({snake_to_camel(segment[1:-1])})}}"
            if segment.startswith("{")
            else segment
            for segment in operation.segments
        )
        base = "mediaUrl" if operation.direct_media else "stationUrl"
        url = f"new URL(`/{path}`, {base})"
        body = ", body" if operation.body else ""
        lines += [
            f"    /** {operation.summary} */",
            f"    {operation.camel_name}({', '.join(parameters)}) {{",
        ]
        match operation.reply:
            case NonJsonReply.FILE:
                lines.append(
                    f'      return stationBinaryEffect({url}, "{operation.method}"{body});'
                )
            case NonJsonReply.UNIT:
                lines.append(
                    f'      return stationVoidEffect({url}, "{operation.method}"{body});'
                )
            case JsonReply(schema):
                parser = typescript_parser(schema)
                lines.append(
                    f'      return stationParsedJsonEffect({url}, "{operation.method}", (payload) => {parser}.parse(payload){body});'
                )
            case _:
                assert_never(operation.reply)
        lines += ["    },"]
    lines += [
        "  };",
        "}",
        "",
        "type PromiseRoutes<Routes> = {",
        "  [Key in keyof Routes]: Routes[Key] extends (...args: infer Arguments) => Effect.Effect<infer Result, unknown, HttpClient.HttpClient>",
        "    ? (...args: Arguments) => Promise<Result> : never;",
        "};",
        "",
        "/** Promise adapter for the generated station routes. */",
        "export function createStationApi(stationUrl: string | URL, mediaUrl: string | URL, signal?: AbortSignal) {",
        "  const routes = createStationEffectApi(stationUrl, mediaUrl);",
        "  return Object.fromEntries(Object.entries(routes).map(([name, route]) => [",
        "    name,",
        "    async (...args: unknown[]) => runStationEffect((route as (...args: unknown[]) => Effect.Effect<unknown, unknown, HttpClient.HttpClient>)(...args), signal),",
        "  ])) as PromiseRoutes<typeof routes>;",
        "}",
    ]
    return "\n".join(lines) + "\n"


def generate(schema: object, targets: frozenset[SdkTarget]) -> None:
    operations = parse_operations(schema)
    if SdkTarget.RUST in targets:
        RUST_PATH.parent.mkdir(parents=True, exist_ok=True)
        RUST_PATH.write_text(generate_rust(operations))
    if SdkTarget.TYPESCRIPT in targets:
        TYPESCRIPT_PATH.write_text(generate_typescript(operations))
