import re
from dataclasses import dataclass
from pathlib import Path

from rua_dev.models import SdkTarget

RUST_PATH = Path("sdk/src/generated/http_routes.rs")
TYPESCRIPT_PATH = Path("typescript-client/src/generated/http-routes.ts")
HEADER = "Generated by rua-dev contracts from schemas/openapi.json."


@dataclass(frozen=True)
class Reply:
    kind: str
    schema: dict | None = None


@dataclass(frozen=True)
class Operation:
    name: str
    method: str
    path: str
    direct_media: bool
    summary: str
    path_parameters: list[str]
    body: dict | None
    reply: Reply
    sends_lease_token: bool

    @property
    def segments(self) -> list[str]:
        return self.path.strip("/").split("/")

    @property
    def camel_name(self) -> str:
        return snake_to_camel(self.name)


def snake_to_camel(name: str) -> str:
    first, *rest = name.split("_")
    return first + "".join(part.capitalize() for part in rest)


def load_operations(document: dict) -> list[Operation]:
    components = document["components"]["schemas"]
    operations = []
    for path, methods in document["paths"].items():
        for method, operation in methods.items():
            if not operation["x-sdk"]:
                continue
            ok = next(
                response
                for status, response in operation["responses"].items()
                if status != "default"
            )
            content = ok.get("content")
            if content is None:
                reply = Reply("unit")
            elif "application/json" in content:
                schema = content["application/json"]["schema"]
                reply = (
                    Reply("unit")
                    if schema == {"type": "null"}
                    else Reply("json", schema)
                )
            else:
                reply = Reply("file")
            body = operation.get("requestBody")
            operations.append(
                Operation(
                    name=operation["operationId"],
                    method=method.upper(),
                    path=path,
                    direct_media=operation.get("x-direct-media", False),
                    summary=operation["summary"],
                    path_parameters=re.findall(r"\{(\w+)\}", path),
                    body=body["content"]["application/json"]["schema"]
                    if body
                    else None,
                    reply=reply,
                    sends_lease_token=bool(
                        body
                        and "lease_token"
                        in components.get(
                            reference_name(
                                body["content"]["application/json"]["schema"]
                            )
                            or "",
                            {},
                        ).get("properties", {})
                    ),
                )
            )
    return operations


def reference_name(schema: dict) -> str | None:
    return schema["$ref"].rsplit("/", 1)[1] if "$ref" in schema else None


def nullable_inner(schema: dict) -> dict | None:
    alternatives = schema.get("anyOf")
    if alternatives and len(alternatives) == 2:
        inner = [alt for alt in alternatives if alt != {"type": "null"}]
        if len(inner) == 1:
            return inner[0]
    return None


def rust_type(schema: dict) -> str:
    inner = nullable_inner(schema)
    if inner is not None:
        return f"Option<{rust_type(inner)}>"
    name = reference_name(schema)
    if name:
        return name
    match schema["type"]:
        case "string":
            return "String"
        case "boolean":
            return "bool"
        case "array":
            return f"Vec<{rust_type(schema['items'])}>"
    raise ValueError(f"unsupported schema {schema}")


def rust_names(schema: dict) -> set[str]:
    return {
        match
        for match in re.findall(r"[A-Z]\w+", rust_type(schema))
        if match not in {"String", "Vec", "Option"}
    }


def rust_segments(operation: Operation) -> str:
    return ", ".join(
        segment[1:-1] if segment.startswith("{") else f'"{segment}"'
        for segment in operation.segments
    )


def generate_rust(operations: list[Operation]) -> str:
    names = set()
    for operation in operations:
        for schema in (operation.body, operation.reply.schema):
            if schema:
                names |= rust_names(schema)
    lines = [
        f"// {HEADER}",
        "use hebbian_contracts::{" + ", ".join(sorted(names)) + "};",
        "use reqwest::{Method, Response};",
        "",
        "use crate::{Result, Station};",
        "",
        "impl Station {",
    ]
    for operation in operations:
        parameters = ["&self"]
        parameters += [f"{name}: &str" for name in operation.path_parameters]
        if operation.body:
            parameters.append(f"body: &{rust_type(operation.body)}")
        returns = {
            "unit": "()",
            "file": "Response",
            "json": rust_type(operation.reply.schema or {})
            if operation.reply.schema
            else "",
        }[operation.reply.kind]
        base = "&self.media_server" if operation.direct_media else "&self.server"
        body = "Some(body)" if operation.body else "None::<&()>"
        call = (
            f"self.request(Method::{operation.method}, {base}, "
            f"&[{rust_segments(operation)}], {body}).await"
        )
        # INVARIANT: The lease token never leaves the SDK: `LeaseGuard` sends these routes.
        visibility = "pub(crate) " if operation.sends_lease_token else "pub "
        lines += [
            f"    /// {operation.summary}",
            "    ///",
            "    /// # Errors",
            "    /// [`crate::Error::Http`] with the service's status, or [`crate::Error::Connection`].",
            f"    {visibility}async fn {operation.name}({', '.join(parameters)}) -> Result<{returns}> {{",
        ]
        match operation.reply.kind:
            case "file":
                lines.append(f"        {call}")
            case "unit":
                lines += [f"        {call}?;", "        Ok(())"]
            case _:
                lines.append(f"        Ok({call}?.json().await?)")
        lines += ["    }", ""]
    lines[-1] = "}"
    return "\n".join(lines) + "\n"


def typescript_parser(schema: dict) -> str | None:
    inner = nullable_inner(schema)
    if inner is not None:
        parser = typescript_parser(inner)
        return None if parser is None else f"{parser}.nullable()"
    name = reference_name(schema)
    if name:
        return f"apiSchemas.shape.{name}"
    match schema["type"]:
        case "string":
            return "z.string()"
        case "boolean":
            return "z.boolean()"
        case "array":
            item = typescript_parser(schema["items"])
            return None if item is None else f"z.array({item})"
    raise ValueError(f"unsupported schema {schema}")


def typescript_body_type(schema: dict) -> str:
    name = reference_name(schema)
    assert name
    return f'ApiSchemas["{name}"]'


def generate_typescript(operations: list[Operation]) -> str:
    lines = [
        f"// {HEADER}",
        'import { z } from "zod";',
        "",
        'import { type ApiSchemas, apiSchemas } from "./api-schemas.js";',
        'import { jsonRequestInit, stationFetch, stationRequest } from "../station-request.js";',
        "",
        "/** One method per station HTTP route; the media service has its own address. */",
        "export function createStationApi(stationUrl: string | URL, mediaUrl: string | URL, signal?: AbortSignal) {",
        "  return {",
    ]
    for operation in operations:
        parameters = [
            f"{snake_to_camel(name)}: string" for name in operation.path_parameters
        ]
        if operation.body:
            parameters.append(f"body: {typescript_body_type(operation.body)}")
        path = "/".join(
            f"${{encodeURIComponent({snake_to_camel(segment[1:-1])})}}"
            if segment.startswith("{")
            else segment
            for segment in operation.segments
        )
        base = "mediaUrl" if operation.direct_media else "stationUrl"
        init = f'jsonRequestInit("{operation.method}", {"body" if operation.body else "undefined"}, signal)'
        url = f"new URL(`/{path}`, {base})"
        lines += [
            f"    /** {operation.summary} */",
            f"    async {operation.camel_name}({', '.join(parameters)}) {{",
        ]
        parser = (
            typescript_parser(operation.reply.schema)
            if operation.reply.kind == "json" and operation.reply.schema
            else None
        )
        match operation.reply.kind:
            case "file":
                lines.append(f"      return stationFetch({url}, {init});")
            case "unit":
                lines.append(f"      await stationFetch({url}, {init});")
            case _ if parser:
                lines.append(
                    f"      return {parser}.parse(await stationRequest({url}, {init}));"
                )
            case _:
                lines.append(f"      return stationRequest({url}, {init});")
        lines += ["    },"]
    lines += ["  };", "}"]
    return "\n".join(lines) + "\n"


def generate(schema: dict, targets: frozenset[SdkTarget]) -> None:
    operations = load_operations(schema)
    if SdkTarget.RUST in targets:
        RUST_PATH.parent.mkdir(parents=True, exist_ok=True)
        RUST_PATH.write_text(generate_rust(operations))
    if SdkTarget.TYPESCRIPT in targets:
        TYPESCRIPT_PATH.write_text(generate_typescript(operations))
