"""Generate the per-command wrapper methods of the Rust, Python and TypeScript SDKs.

Reads the `StationCommand` variants from schemas/openapi.json, whose `ClientMessage` component
holds the Rust type in contracts/src/station_api.rs, so the three SDKs cannot drift.
"""

from dataclasses import dataclass
from pathlib import Path

from rua_dev.models import SdkTarget

RUST_PATH = Path("sdk/src/generated/station_commands.rs")
PYTHON_PATH = Path("hebbian_rua/client/contract/arm_commands.py")
TYPESCRIPT_PATH = Path("typescript-client/src/generated/arm-commands.ts")
# The one place that says which commands need no lease: power, fault recovery and stop. Every
# other StationCommand moves the arm, so the SDKs put it on the lease handle only; a new motion
# command lands there without being listed.
LEASE_FREE_COMMANDS = frozenset(
    {"enable", "disable", "clear_fault", "approve_recovery", "stop"}
)
HEADER = "Generated by rua-dev contracts from StationCommand."


@dataclass(frozen=True)
class Field:
    name: str
    required: bool
    schema: dict
    description: str


@dataclass(frozen=True)
class Variant:
    kind: str
    title: str
    description: str
    fields: list[Field]

    @property
    def needs_lease(self) -> bool:
        return self.kind not in LEASE_FREE_COMMANDS

    @property
    def pascal_name(self) -> str:
        return "".join(part.capitalize() for part in self.kind.split("_"))

    @property
    def camel_name(self) -> str:
        pascal = self.pascal_name
        return pascal[0].lower() + pascal[1:]


def load_definitions(schema: dict) -> dict:
    return schema["components"]["schemas"]


def reference_name(schema: dict) -> str:
    return schema["$ref"].rsplit("/", 1)[1]


def load_variants(definitions: dict) -> list[Variant]:
    variants = []
    for variant in definitions["StationCommand"]["oneOf"]:
        properties = dict(variant["properties"])
        kind = properties.pop("kind")["const"]
        required = variant.get("required", [])
        required_names = [name for name in required if name in properties]
        optional_names = [name for name in properties if name not in required_names]
        fields = [
            Field(
                name=name,
                required=name in required_names,
                schema=properties[name],
                description=properties[name].get("description", ""),
            )
            for name in required_names + optional_names
        ]
        variants.append(
            Variant(
                kind=kind,
                title=variant["title"],
                description=variant["description"],
                fields=fields,
            )
        )
    return variants


def scalar_type(schema: dict) -> str:
    """The JSON type of a schema once `null` is dropped."""
    declared = schema["type"]
    if isinstance(declared, list):
        declared = next(name for name in declared if name != "null")
    return declared


def fixed_length(schema: dict) -> int | None:
    if schema.get("minItems") is not None and schema.get("minItems") == schema.get(
        "maxItems"
    ):
        return schema["minItems"]
    return None


def rust_type(schema: dict, definitions: dict) -> str:
    if "$ref" in schema:
        return reference_name(schema)
    kind = scalar_type(schema)
    if kind == "number":
        return "f64"
    if kind == "string":
        return "String"
    if kind == "array":
        item = rust_type(schema["items"], definitions)
        length = fixed_length(schema)
        return f"[{item}; {length}]" if length else f"Vec<{item}>"
    raise ValueError(f"unsupported schema {schema}")


def python_type(schema: dict, definitions: dict) -> str:
    if "$ref" in schema:
        alternatives = definitions[reference_name(schema)]["oneOf"]
        return " | ".join(alternative["title"] for alternative in alternatives)
    kind = scalar_type(schema)
    if kind == "number":
        return "float"
    if kind == "string":
        return "str"
    if kind == "array":
        return f"list[{python_type(schema['items'], definitions)}]"
    raise ValueError(f"unsupported schema {schema}")


def python_names(schema: dict, definitions: dict) -> set[str]:
    """The contract classes a Python annotation uses."""
    if "$ref" in schema:
        return {alt["title"] for alt in definitions[reference_name(schema)]["oneOf"]}
    if scalar_type(schema) == "array":
        return python_names(schema["items"], definitions)
    return set()


def snake_to_camel(name: str) -> str:
    first, *rest = name.split("_")
    return first + "".join(part.capitalize() for part in rest)


def doc_lines(variant: Variant) -> list[str]:
    lines = variant.description.split("\n")
    described = [field for field in variant.fields if field.description]
    if described:
        lines.append("")
        lines.extend(f"`{field.name}`: {field.description}" for field in described)
    return lines


def generate_rust(variants: list[Variant], definitions: dict) -> str:
    reference_types = sorted(
        {
            reference_name(field.schema)
            for variant in variants
            for field in variant.fields
            if "$ref" in field.schema
        }
        | {
            reference_name(field.schema["items"])
            for variant in variants
            for field in variant.fields
            if "items" in field.schema and "$ref" in field.schema["items"]
        }
    )
    lines = [
        f"// {HEADER}",
        f"use hebbian_contracts::{{CommandRecord, StationCommand, {', '.join(reference_types)}}};",
        "",
        "use crate::{CommandOptions, LeaseGuard, Result, Station};",
        "",
    ]
    for owner, receiver, needs_lease in (
        ("Station", "self", False),
        ("LeaseGuard", "self.station", True),
    ):
        lines.append(f"impl {owner} {{")
        lines.extend(
            rust_methods(
                [v for v in variants if v.needs_lease == needs_lease],
                definitions,
                receiver,
            )
        )
        lines += ["}", ""]
    return "\n".join(lines).rstrip() + "\n"


def rust_methods(
    variants: list[Variant], definitions: dict, receiver: str
) -> list[str]:
    lines: list[str] = []
    for variant in variants:
        parameters = ["&self", "arm: &str"]
        assignments = []
        for field in variant.fields:
            inner = rust_type(field.schema, definitions)
            parameters.append(
                f"{field.name}: {inner if field.required else f'Option<{inner}>'}"
            )
            assignments.append(field.name)
        if assignments:
            body = (
                f"StationCommand::{variant.pascal_name} {{ {', '.join(assignments)} }}"
            )
        else:
            body = f"StationCommand::{variant.pascal_name}"
        docs = [f"    /// {line}".rstrip() for line in doc_lines(variant)]
        lines.extend(docs)
        lines += ["    ///", "    /// # Errors", "    /// As [`Station::run`]."]
        lines.append(
            f"    pub async fn {variant.kind}({', '.join(parameters)}) -> Result<CommandRecord> {{"
        )
        arguments = ", ".join(["arm", *assignments, "CommandOptions::default()"])
        lines += [
            f"        self.{variant.kind}_with({arguments}).await",
            "    }",
            "",
        ]
        lines.extend(docs)
        lines += ["    ///", "    /// # Errors", "    /// As [`Station::run_with`]."]
        lines.append(
            f"    pub async fn {variant.kind}_with({', '.join([*parameters, 'options: CommandOptions'])}) -> Result<CommandRecord> {{"
        )
        run_method = "run_with_lease" if receiver == "self.station" else "run_with"
        target = "self" if receiver == "self.station" else receiver
        lines += [
            f"        {target}.{run_method}(arm, {body}, options).await",
            "    }",
            "",
        ]
    lines.pop()
    return lines


def generate_python(variants: list[Variant], definitions: dict) -> str:
    imported = {variant.title for variant in variants}
    for variant in variants:
        for field in variant.fields:
            imported |= python_names(field.schema, definitions)
    lines = [
        f'"""{HEADER}"""',
        "",
        "from typing import TYPE_CHECKING",
        "",
        "from hebbian_rua.client.contract.station_api import (",
        *[f"    {name}," for name in sorted(imported)],
        ")",
        "",
        "if TYPE_CHECKING:",
        "    from hebbian_rua.client.station_types import CommandResult, StationCommand",
    ]
    for class_name, needs_lease, summary in (
        (
            "ArmPowerCommands",
            False,
            "Power, fault recovery and stop, which need no lease",
        ),
        (
            "ArmMotionCommands",
            True,
            "The commands that move the arm, which need the lease",
        ),
    ):
        lines += [
            "",
            "",
            f"class {class_name}:",
            f'    """{summary}; a subclass supplies `_run_command`."""',
            "",
            "    async def _run_command(",
            "        self,",
            '        command: "StationCommand",',
            "        *,",
            "        expected_revision: int | None = None,",
            '    ) -> "CommandResult":',
            "        raise NotImplementedError",
            "",
        ]
        for variant in variants:
            if variant.needs_lease == needs_lease:
                lines.extend(python_method(variant, definitions))
    return "\n".join(lines).rstrip() + "\n"


def python_method(variant: Variant, definitions: dict) -> list[str]:
    required = [field for field in variant.fields if field.required]
    optional = [field for field in variant.fields if not field.required]
    parameters = ["self"]
    parameters += [
        f"{field.name}: {python_type(field.schema, definitions)}" for field in required
    ]
    parameters.append("*")
    parameters += [
        f"{field.name}: {python_type(field.schema, definitions)} | None = None"
        for field in optional
    ]
    parameters.append("expected_revision: int | None = None")
    arguments = ", ".join(f"{field.name}={field.name}" for field in variant.fields)
    docstring = "\n".join(f"        {line}".rstrip() for line in doc_lines(variant))
    return [
        f'    async def {variant.kind}({", ".join(parameters)}) -> "CommandResult":',
        '        """' + docstring.lstrip(),
        '        """',
        f"        return await self._run_command({variant.title}({arguments}), expected_revision=expected_revision)",
        "",
    ]


def typescript_type(variant: Variant, field: Field) -> str:
    access = f'Extract<StationCommand, {{ kind: "{variant.kind}" }}>["{field.name}"]'
    return access if field.required else f"NonNullable<{access}>"


def generate_typescript(variants: list[Variant]) -> str:
    lines = [
        f"// {HEADER}",
        'import type { StationCommand } from "../station-types.js";',
    ]
    for function_name, needs_lease, summary in (
        (
            "armPowerCommands",
            False,
            "power, fault recovery and stop, which need no lease",
        ),
        (
            "armMotionCommands",
            True,
            "the commands that move the arm, which need the lease",
        ),
    ):
        lines += [
            "",
            f"/** One method per command for {summary}, each sending its command, and the arm revision it was planned on, through `send`. */",
            f"export function {function_name}<Result>(",
            "  send: (command: StationCommand, expectedRevision?: number) => Result,",
            ") {",
            "  return {",
        ]
        for variant in variants:
            if variant.needs_lease == needs_lease:
                lines.extend(typescript_method(variant))
        lines += ["  };", "}"]
    return "\n".join(lines) + "\n"


def typescript_method(variant: Variant) -> list[str]:
    lines = ["    /**"]
    lines.extend(f"     * {line}".rstrip() for line in doc_lines(variant))
    lines.append("     */")
    parameters = []
    entries = [f'kind: "{variant.kind}"']
    for field in variant.fields:
        name = snake_to_camel(field.name)
        optional_mark = "" if field.required else "?"
        parameters.append(f"{name}{optional_mark}: {typescript_type(variant, field)}")
        entries.append(
            f"{field.name}: {name}"
            if field.required
            else f"{field.name}: {name} ?? null"
        )
    parameters.append("expectedRevision?: number")
    lines += [
        f"    {variant.camel_name}({', '.join(parameters)}): Result {{",
        f"      return send({{ {', '.join(entries)} }}, expectedRevision);",
        "    },",
    ]
    return lines


def generate(schema: dict, targets: frozenset[SdkTarget]) -> None:
    definitions = load_definitions(schema)
    variants = load_variants(definitions)
    if SdkTarget.RUST in targets:
        RUST_PATH.parent.mkdir(parents=True, exist_ok=True)
        RUST_PATH.write_text(generate_rust(variants, definitions))
    if SdkTarget.PYTHON in targets:
        PYTHON_PATH.write_text(generate_python(variants, definitions))
    if SdkTarget.TYPESCRIPT in targets:
        TYPESCRIPT_PATH.write_text(generate_typescript(variants))
